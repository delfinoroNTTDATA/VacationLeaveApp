export function currentLang(): LangCode {
    return LOCALES[CAL.local].lang;
}

export function monthNames(): string[] {
  return I18N[currentLang()].months as string[]
}

export function t(key: string): string {
    const lang = currentLang();
    const val = (I18N[lang] && I18N[lang][key]) || I18N.it[key];

    return typeof val === 'string' ? val : key;
}

export function tn(key: string, params?: Record<string, string | number>): string {
    let s = t(key);

    for (const [k,v] of Object.entries(params || {})) {
        s = s.split('{'+ k + '}').join(String(v));
    }

    return s;
}