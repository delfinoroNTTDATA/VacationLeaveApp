interface LangContextType{
    local: string;
    lang: Lang;
    country: string;
    setLocal: (code: string) => void;
    t: (key: string) => any;
}

const LangContext = createContext<LangContextType>({
    local: DEFAULT_LOCAL, lang: 'it', country: 'IT', setLocal: () => {}, t: (k) => k,
});

export function LangProvider({ children } : { children: ReactNode }) {
    const [local, setLocalState] = useState<string>(DEFAULT_LOCAL);

    useEffect(() => {
        AsyncStorage.getItem('leave_local').then(v => {
            if(v && LOCALES[v]) setLocalState(v);
        })
    }, []);

    const setLocal = (code : string) => {
        if(!LOCALES[code]) return;
        setLocalState(code);
        AsyncStorage.setItem('leave_local', code);
    }

    const def = LOCALES[local] || LOCALES[DEFAULT_LOCAL];
    
    const t = (key: string) =>  (TRANSLATIONS[def.lang] as any)[key] ?? (TRANSLATIONS.it as any)[key] ?? key;

    return (
        <LangContext.Provider value={{ local, lang: def.lang, country: def.country, setLocal, t }}>
            {children}
        </LangContext.Provider>
    );
}

export function useLang() { return useContext(LangContext); }